function validateRegisterStep(step, formData) {
    const errors = {};

    if (step === 1) {
        if (!formData.institutionName.trim()) errors.institutionName = 'Institution Name is required.';
        if (!formData.accreditationId.trim()) errors.accreditationId = 'Accreditation ID / Registration Number is required.';
    }

    if (step === 2) {
        if (!formData.representativeName.trim()) errors.representativeName = 'Representative Full Name is required.';
        if (!formData.representativeEmail.trim()) {
            errors.representativeEmail = 'Official Email is required.';
        } else if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(formData.representativeEmail)) {
            errors.representativeEmail = 'Please enter a valid email address.';
        }
    }

    if (step === 3) {
        if (!formData.walletAddress) errors.walletAddress = 'Please connect wallet to continue.';
        if (!formData.network) errors.network = 'Please select a network.';
        if (!formData.authorizedConfirm) errors.authorizedConfirm = 'Authorization confirmation is required.';
        if (!formData.termsConfirm) errors.termsConfirm = 'Terms and Compliance confirmation is required.';
    }

    return errors;
}

