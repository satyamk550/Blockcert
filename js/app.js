function handleLegacyIndexViews(currentPage) {
    if (isDedicatedApplicationPage(currentPage)) {
        return;
    }

    const view = new URLSearchParams(window.location.search).get('view');
    if (view === 'student') {
        const studentRoll = sessionStorage.getItem('studentRollNumber');
        if (studentRoll) {
            if (!navigateToMappedRoute('/student/dashboard')) {
                window.location.href = 'student-dashboard.html';
            }
        } else if (!navigateToMappedRoute('/student/login')) {
            window.location.href = 'student-login.html';
        }
        return;
    }

    if (view === 'verifier') {
        if (!navigateToMappedRoute('/verifier')) {
            window.location.href = 'verification.html';
        }
        return;
    }

    const validViews = new Set(['home', 'student']);
    showSection(validViews.has(view) ? view : 'home');
}

