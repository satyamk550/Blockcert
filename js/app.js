function validateInstitutionIssueForm(formState, files) {
    const errors = {};

    if (!formState.studentName.trim()) {
        errors.studentName = 'Student Name is required.';
    }
    if (!formState.rollNumber.trim()) {
        errors.rollNumber = 'Roll Number is required.';
    }
    if (!formState.department.trim()) {
        errors.department = 'Department is required.';
    }
    if (!formState.yearOfPassing.trim()) {
        errors.yearOfPassing = 'Year of Passing is required.';
    }
    if (!formState.classDivision.trim()) {
        errors.classDivision = 'Class / Division is required.';
    }
    if (!formState.scoreValue.trim()) {
        errors.scoreValue = 'CGPA / Percentage is required.';
    }

    if (!files.certificatePdf) {
        errors.certificatePdf = 'Certificate PDF is required.';
    } else if (!/\.pdf$/i.test(files.certificatePdf.name || '') && files.certificatePdf.type !== 'application/pdf') {
        errors.certificatePdf = 'Please upload a valid PDF certificate.';
    }

    if (!files.studentPhoto) {
        errors.studentPhoto = 'Student Photo is required.';
    } else if (files.studentPhoto.type && !files.studentPhoto.type.startsWith('image/')) {
        errors.studentPhoto = 'Please upload a valid student photo.';
    }

    return errors;
}

