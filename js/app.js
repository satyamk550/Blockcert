function bindLegacyCredentialRecorder() {
    const recordCredentialBtn = document.getElementById('recordCredentialBtn');
    const recordLog = document.getElementById('recordLog');

    if (!recordCredentialBtn || !recordLog) {
        return;
    }

    recordCredentialBtn.addEventListener('click', () => {
        const studentName = document.getElementById('issueStudentName')?.value.trim() || '';
        const certificateTitle = document.getElementById('issueCertificateTitle')?.value.trim() || '';
        const courseProgram = document.getElementById('issueCourseProgram')?.value.trim() || '';
        const issueDate = document.getElementById('issueDate')?.value.trim() || '';
        const issueFile = document.getElementById('issueCertificateFile')?.files?.[0];

        if (!studentName || !certificateTitle || !courseProgram || !issueDate || !issueFile) {
            recordLog.textContent = 'Please complete all issue credential fields before issuing.';
            recordLog.classList.remove('hidden');
            return;
        }

        recordLog.textContent = 'Generating credential hash and writing to blockchain...';
        recordLog.classList.remove('hidden');

        setTimeout(() => {
            const payload = `${studentName}|${certificateTitle}|${courseProgram}|${issueDate}|${issueFile.name}`;
            const txHash = pseudoBlockchainHash(payload);
            recordLog.textContent = `Credential issued successfully. Transaction hash: ${txHash}`;
        }, 1700);
    });
}

function bindInstitutionLogin() {
    const institutionLoginForm = document.getElementById('institutionLoginForm');
    const institutionEmail = document.getElementById('institutionEmail');
    const institutionPassword = document.getElementById('institutionPassword');
    const institutionLoginError = document.getElementById('institutionLoginError');
    const institutionLoginStatus = document.getElementById('institutionLoginStatus');

    if (!institutionLoginForm || !institutionEmail || !institutionPassword || !institutionLoginError) {
        return;
    }

    const VALID_EMAIL = 'admin@blockcert.edu';
    const VALID_PASSWORD = 'BlockCert123';

    const clearError = () => {
        institutionLoginError.classList.add('hidden');
        if (institutionLoginStatus) {
            institutionLoginStatus.classList.add('hidden');
        }
    };

    institutionEmail.addEventListener('input', clearError);
    institutionPassword.addEventListener('input', clearError);

    institutionLoginForm.addEventListener('submit', (event) => {
        event.preventDefault();
        const emailValue = institutionEmail.value.trim();
        const passwordValue = institutionPassword.value;

        if (emailValue === VALID_EMAIL && passwordValue === VALID_PASSWORD) {
            if (document.body.dataset.page === 'institution') {
                if (institutionLoginStatus) {
                    institutionLoginStatus.classList.remove('hidden');
                }
                return;
            }

            if (!navigateToMappedRoute('/institution/dashboard')) {
                window.location.href = 'institution-dashboard.html';
            }
            return;
        }

        institutionLoginError.classList.remove('hidden');
        if (institutionLoginStatus) {
            institutionLoginStatus.classList.add('hidden');
        }
    });
}

function bindStudentLogin() {
    const studentLoginForm = document.getElementById('studentLoginForm');
    const studentRollNumber = document.getElementById('studentRollNumber');
    const studentPassword = document.getElementById('studentPassword');
    const studentLoginError = document.getElementById('studentLoginError');

    if (!studentLoginForm || !studentRollNumber || !studentPassword || !studentLoginError) {
        return;
    }

    const clearStudentError = () => {
        studentLoginError.classList.add('hidden');
    };

    studentRollNumber.addEventListener('input', clearStudentError);
    studentPassword.addEventListener('input', clearStudentError);

    studentLoginForm.addEventListener('submit', (event) => {
        event.preventDefault();
        const rollValue = studentRollNumber.value.trim();
        const passwordValue = studentPassword.value;

        if (!rollValue || !passwordValue) {
            studentLoginError.classList.remove('hidden');
            return;
        }

        try {
            sessionStorage.setItem('studentRollNumber', rollValue);
        } catch (error) {
            console.error('Unable to save student login session:', error);
        }

        const submitButton = studentLoginForm.querySelector('button[type="submit"]');
        if (submitButton) {
            submitButton.textContent = 'Signing In...';
            submitButton.setAttribute('disabled', 'disabled');
        }

        setTimeout(() => {
            if (!navigateToMappedRoute('/student/dashboard')) {
                window.location.href = 'student-dashboard.html';
            }
        }, 500);
    });
}

